a("function Uc = resuelve(K, Fc, kc_i, kb_i, n_p, n_g)")
a("  c_on = ones(n_p, 1)")
a("  b_on = zeros(n_p, 1)")
a("  cambia = 1")
a("  iters = 0")
a("  Uc = zeros(n_g, 1)")
a("  while cambia > 0 && iters < 30")
a("    Kt = K")
a("    for q = 1:n_p")
a("      d3 = 6·(q - 1) + 3")
a("      Kt(d3, d3) = Kt(d3, d3) + c_on(q)·kc_i(q) + b_on(q)·kb_i(q)")
a("    end")
a("    for d = [6·(41 - 1) + 1, 6·(41 - 1) + 2, 6·(45 - 1) + 2]")
