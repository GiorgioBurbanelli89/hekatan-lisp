a("function R = aisc(P, M, N_p, B_p, f_b, f_pmax, q_max, m_c, u_t, F_y)")
a("  e = M/P")
a("  e_cr = N_p/2 - P/(2·q_max)")
a("  if e <= e_cr")
a("    Y = N_p - 2·e")
a("    T = 0")
a("    f_p = P/(Y·B_p)")
a("  else")
a("    Y = (f_b + N_p/2) - sqrt((f_b + N_p/2)^2 - 2·P·(e + f_b)/q_max)")
a("    T = q_max·Y - P")
a("    f_p = f_pmax")
a("  end")
a("  if Y >= m_c")
a("    Mc = f_p·m_c^2/2")
a("  else")
a("    Mc = f_p·Y·(m_c - Y/2)")
a("  end")
a("  Mt = T·u_t/B_p")
a("  t_r = sqrt(4·max(Mc, Mt)/(0.9·F_y))")
a("  R = [e; e_cr; Y; T; f_p; Mc; Mt; t_r]")
a("end")
a("#show")
a("A_r = aisc(N_c, M_x, N_p, B_p, f_b, f_pmax, q_max, m_c, u_t, F_y) 'e · e_crít · Y · T · f_p · M_contacto · M_perno · t_req")
a("#: **Excentricidad.** e = M/P se compara con la crítica e_crít = N/2 − P/(2·q_max): por debajo, la placa solo comprime (longitud de apoyo Y = N − 2e, bloque uniforme f_p = P/(Y·B)); por encima, la placa se levanta, los pernos de ese lado trabajan con T = q_max·Y − P y Y sale de la ecuación de momentos respecto de los pernos.")
