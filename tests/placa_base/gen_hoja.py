a("      Kt(:, d) = 0")
a("      Kt(d, d) = 1")
a("    end")
a("    Ft = Fc")
a("    for d = [6·(41 - 1) + 1, 6·(41 - 1) + 2, 6·(45 - 1) + 2]")
a("      Ft(d) = 0")
a("    end")
a("    Uc = clsolve(Kt, Ft)")
a("    cambia = 0")
a("    for q = 1:n_p")
a("      uz = Uc(6·(q - 1) + 3)")
a("      if c_on(q) == 1 && uz > 0")
a("        c_on(q) = 0")
a("        cambia = cambia + 1")
a("      end")
a("      if c_on(q) == 0 && uz < 0")
a("        c_on(q) = 1")
a("        cambia = cambia + 1")
a("      end")
a("      if kb_i(q) > 0")
a("        if b_on(q) == 0 && uz > 0")
a("          b_on(q) = 1")
a("          cambia = cambia + 1")
a("        end")
a("        if b_on(q) == 1 && uz < 0")
a("          b_on(q) = 0")
a("          cambia = cambia + 1")
a("        end")
a("      end")
a("    end")
a("    iters = iters + 1")
a("  end")
a("end")
